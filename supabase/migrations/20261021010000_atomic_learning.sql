CREATE OR REPLACE FUNCTION public.consume_ai_quota(p_service text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE own_id uuid := auth.uid(); allowed_count integer; used integer; premium boolean;
BEGIN
  IF own_id IS NULL THEN RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '42501'; END IF;
  IF p_service NOT IN ('chat', 'tts') THEN RAISE EXCEPTION 'invalid_service'; END IF;
  SELECT plan = 'premium' AND (premium_until IS NULL OR premium_until > now()) INTO premium FROM public.profiles WHERE id = own_id;
  allowed_count := CASE WHEN p_service = 'chat' THEN CASE WHEN premium THEN 200 ELSE 20 END ELSE CASE WHEN premium THEN 400 ELSE 40 END END;
  INSERT INTO public.ai_usage(user_id, service) VALUES (own_id, p_service) ON CONFLICT DO NOTHING;
  UPDATE public.ai_usage SET requests = requests + 1
  WHERE user_id = own_id AND service = p_service AND usage_day = current_date AND requests < allowed_count RETURNING requests INTO used;
  RETURN used IS NOT NULL;
END;
$$;
REVOKE ALL ON FUNCTION public.consume_ai_quota(text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.consume_ai_quota(text) TO authenticated;

