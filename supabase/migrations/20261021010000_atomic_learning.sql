CREATE OR REPLACE FUNCTION public.complete_lesson_atomic(p_lesson_id text,p_completed_at timestamptz DEFAULT now())
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE
  own_id uuid := auth.uid();
  reward integer;
  previous text;
  total integer;
  studied_at timestamptz := greatest(now()-interval '365 days',least(now(),coalesce(p_completed_at,now())));
BEGIN
  IF own_id IS NULL THEN RAISE EXCEPTION 'not_authenticated' USING ERRCODE = '42501'; END IF;
  SELECT xp INTO reward FROM public.lesson_catalog WHERE id = p_lesson_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'unknown_lesson' USING ERRCODE = '22023'; END IF;
  -- A lock per profile serializes different lessons too, preventing lost XP.
  SELECT coalesce(xp, 0) INTO total FROM public.profiles WHERE id = own_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'profile_missing'; END IF;
  SELECT status INTO previous FROM public.lesson_progress WHERE user_id = own_id AND lesson_id = p_lesson_id;
  INSERT INTO public.learning_activity(user_id,event_key,created_at) VALUES(own_id,'study:'||studied_at::date::text,studied_at) ON CONFLICT DO NOTHING;
  IF previous = 'completed' THEN
    RETURN jsonb_build_object('success', true, 'alreadyCompleted', true, 'xpEarned', 0, 'totalXP', total);
  END IF;
  INSERT INTO public.lesson_progress(user_id, lesson_id, status, progress, xp_earned, completed_at, updated_at)
  VALUES (own_id, p_lesson_id, 'completed', 100, reward, studied_at, now())
  ON CONFLICT (user_id, lesson_id) DO UPDATE SET status = 'completed', progress = 100,
    xp_earned = reward, completed_at = studied_at, updated_at = now();
  UPDATE public.profiles SET xp = total + reward, updated_at = now() WHERE id = own_id;
  INSERT INTO public.learning_activity(user_id, event_key,created_at) VALUES (own_id, 'lesson:' || p_lesson_id,studied_at) ON CONFLICT DO NOTHING;
  RETURN jsonb_build_object('success', true, 'alreadyCompleted', false, 'xpEarned', reward, 'totalXP', total + reward);
END;
$$;
REVOKE ALL ON FUNCTION public.complete_lesson_atomic(text,timestamptz) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.complete_lesson_atomic(text,timestamptz) TO authenticated;

